"""Write ILLUSTRATIVE / SYNTHETIC sample files for WS2 (BE-7.5, WS2-P0).

Every file is synthetic: generated from a fixed seed, never derived from client data
(D-14), and marked as such inside the file:

* CSV: a first-line comment `# ILLUSTRATIVE / SYNTHETIC ...` before the header row.
* XLSX: the only sheet is named `ILLUSTRATIVE SYNTHETIC` (a sheet name cannot hold "/"),
  and the workbook title carries the full marker.
* JSON: a top-level object whose `marker` key holds the marker; rows are under `records`.

Datasets: `instrument` (CSV), `position` (XLSX) and `cashflow_event` (JSON), with columns
from the illustrative schemas seeded by migration 0007. Each also has deliberately bad
variants (`<dataset>__<variant>.<ext>`), one defect each: a missing required column, a
bad date, an over-scale decimal, a duplicate business key, an unknown extra column,
non-UTF-8 bytes (CSV/JSON only) and a bad currency code.

Output is byte-for-byte reproducible: a fixed seed, no clock, and XLSX written with the
standard library using fixed ZIP timestamps and no compression (zlib builds can differ).
`SHA256SUMS` lists every file's hash.

Usage (from backend/):  python -m scripts.make_synthetic_samples [--out DIR] [--check]
"""

import argparse
import hashlib
import io
import json
import random
import sys
import zipfile
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path
from xml.sax.saxutils import escape

from app.ingestion.constants import SYNTHETIC_MARKER

SEED = 20261016
ROWS = 25
OUT = Path(__file__).resolve().parent.parent / "samples" / "synthetic"
SHEET_NAME = "ILLUSTRATIVE SYNTHETIC"
GENERATOR = "backend/scripts/make_synthetic_samples.py"
NOTE = f"Not client data. Generated by {GENERATOR} (seed {SEED})."

Row = dict[str, str]


@dataclass(frozen=True)
class Dataset:
    name: str
    fmt: str  # csv | xlsx | json
    columns: list[str]
    make_row: Callable[[random.Random, int], Row]
    business_key: str
    required_to_drop: str  # the required column removed by `missing_required_column`
    date_column: str
    decimal_column: str
    decimal_scale: int
    currency_column: str
    text_column: str  # receives non-ASCII text in the `non_utf8` variant
    decimals: frozenset[str] = field(default_factory=frozenset)
    dates: frozenset[str] = field(default_factory=frozenset)


def _money(rng: random.Random, low: int, high: int, scale: int) -> str:
    units = rng.randint(low * 10**scale, high * 10**scale)
    return str(Decimal(units).scaleb(-scale))


def _day(rng: random.Random, start: date, span_days: int) -> str:
    return (start + timedelta(days=rng.randint(0, span_days))).isoformat()


CURRENCIES = ["EUR", "USD", "GBP", "CHF"]


def _instrument(rng: random.Random, i: int) -> Row:
    return {
        "instrument_id": f"INS-{i:06d}",
        "instrument_type": rng.choice(["DEPOSIT", "LOAN", "BOND"]),
        "currency": rng.choice(CURRENCIES),
        "counterparty_id": f"CP-{rng.randint(1, 9999):04d}",
        "product_family": rng.choice(["RETAIL", "CORPORATE", "TREASURY"]),
        "notional": _money(rng, 1_000, 5_000_000, 2),
        "interest_rate": _money(rng, 0, 12, 4),
        "maturity_date": _day(rng, date(2027, 1, 1), 3650),
        "book_code": f"BK-{rng.randint(1, 40):02d}",
    }


def _position(rng: random.Random, i: int) -> Row:
    return {
        "position_id": f"POS-{i:06d}",
        "instrument_id": f"INS-{rng.randint(1, ROWS):06d}",
        "account_id": f"ACC-{rng.randint(1, 99999):05d}",
        "legal_entity_id": rng.choice(["LE-ALPHA", "LE-BETA"]),
        "as_of_date": "2026-09-30",
        "quantity": _money(rng, 1, 100_000, 6),
        "balance": _money(rng, 100, 2_000_000, 2),
        "currency": rng.choice(CURRENCIES),
        "valuation_date": _day(rng, date(2026, 9, 1), 29),
    }


def _cashflow(rng: random.Random, i: int) -> Row:
    return {
        "cashflow_id": f"CF-{i:06d}",
        "instrument_id": f"INS-{rng.randint(1, ROWS):06d}",
        "due_date": _day(rng, date(2026, 10, 1), 720),
        "amount": _money(rng, 10, 250_000, 2),
        "currency": rng.choice(CURRENCIES),
        "cashflow_type": rng.choice(["PRINCIPAL", "INTEREST", "FEE"]),
        "origin": rng.choice(["CONTRACTUAL", "BEHAVIOURAL"]),
    }


DATASETS = [
    Dataset(
        name="instrument",
        fmt="csv",
        columns=list(_instrument(random.Random(0), 1)),
        make_row=_instrument,
        business_key="instrument_id",
        required_to_drop="notional",
        date_column="maturity_date",
        decimal_column="notional",
        decimal_scale=2,
        currency_column="currency",
        text_column="counterparty_id",
    ),
    Dataset(
        name="position",
        fmt="xlsx",
        columns=list(_position(random.Random(0), 1)),
        make_row=_position,
        business_key="position_id",
        required_to_drop="balance",
        date_column="as_of_date",
        decimal_column="balance",
        decimal_scale=2,
        currency_column="currency",
        text_column="legal_entity_id",
        decimals=frozenset({"quantity", "balance"}),
        dates=frozenset({"as_of_date", "valuation_date"}),
    ),
    Dataset(
        name="cashflow_event",
        fmt="json",
        columns=list(_cashflow(random.Random(0), 1)),
        make_row=_cashflow,
        business_key="cashflow_id",
        required_to_drop="due_date",
        date_column="due_date",
        decimal_column="amount",
        decimal_scale=2,
        currency_column="currency",
        text_column="origin",
        decimals=frozenset({"amount"}),
    ),
]


# --- bad variants: (columns, rows) -> (columns, rows), one defect each -------------------

Table = tuple[list[str], list[Row]]


def _missing_required_column(ds: Dataset, t: Table) -> Table:
    cols = [c for c in t[0] if c != ds.required_to_drop]
    return cols, [{c: r[c] for c in cols} for r in t[1]]


def _set(t: Table, row: int, column: str, value: str) -> Table:
    rows = [dict(r) for r in t[1]]
    rows[row][column] = value
    return t[0], rows


def _bad_date(ds: Dataset, t: Table) -> Table:
    return _set(t, 2, ds.date_column, "2026-02-30")


def _over_scale_decimal(ds: Dataset, t: Table) -> Table:
    value = Decimal(t[1][3][ds.decimal_column]) + Decimal(1).scaleb(-(ds.decimal_scale + 3))
    return _set(t, 3, ds.decimal_column, str(value))


def _duplicate_business_key(ds: Dataset, t: Table) -> Table:
    return _set(t, 4, ds.business_key, t[1][0][ds.business_key])


def _unknown_extra_column(ds: Dataset, t: Table) -> Table:
    cols = [*t[0], "legacy_flag"]
    return cols, [{**r, "legacy_flag": "Y" if i % 2 else "N"} for i, r in enumerate(t[1])]


def _non_utf8(ds: Dataset, t: Table) -> Table:
    # Written in cp1252 by the caller: these characters are not valid UTF-8 bytes there.
    return _set(t, 1, ds.text_column, "Société Zürich Ångström")


def _bad_currency_code(ds: Dataset, t: Table) -> Table:
    return _set(t, 5, ds.currency_column, "EURO")


VARIANTS: dict[str, Callable[[Dataset, Table], Table]] = {
    "missing_required_column": _missing_required_column,
    "bad_date": _bad_date,
    "over_scale_decimal": _over_scale_decimal,
    "duplicate_business_key": _duplicate_business_key,
    "unknown_extra_column": _unknown_extra_column,
    "non_utf8": _non_utf8,
    "bad_currency_code": _bad_currency_code,
}
TEXT_ONLY = {"non_utf8"}  # meaningless for XLSX, whose XML parts are always UTF-8


# --- writers -----------------------------------------------------------------------------


def _marker_line(ds: Dataset, variant: str | None) -> str:
    what = f"{ds.name}" + (f", bad variant '{variant}'" if variant else "")
    return f"{SYNTHETIC_MARKER} sample: {what}. {NOTE}"


def _csv(ds: Dataset, t: Table, variant: str | None) -> str:
    def cell(v: str) -> str:
        return f'"{v.replace(chr(34), chr(34) * 2)}"' if any(ch in v for ch in ',"\n') else v

    lines = [f"# {_marker_line(ds, variant)}", ",".join(t[0])]
    lines += [",".join(cell(r[c]) for c in t[0]) for r in t[1]]
    return "\n".join(lines) + "\n"


def _json(ds: Dataset, t: Table, variant: str | None) -> str:
    """Decimals are JSON numbers written from their exact text (never through float)."""

    def value(column: str, v: str) -> str:
        if column in ds.decimals:
            try:
                Decimal(v)
                return v
            except ArithmeticError:
                pass
        return json.dumps(v, ensure_ascii=False)

    records = [
        "    {" + ", ".join(f"{json.dumps(c)}: {value(c, r[c])}" for c in t[0]) + "}" for r in t[1]
    ]
    marker = json.dumps(_marker_line(ds, variant), ensure_ascii=False)
    return '{\n  "marker": ' + marker + ',\n  "records": [\n' + ",\n".join(records) + "\n  ]\n}\n"


_XLSX_EPOCH = date(1899, 12, 30)
_FIXED_TIME = (1980, 1, 1, 0, 0, 0)
_NS = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
_REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
_PKG = "http://schemas.openxmlformats.org/package/2006/relationships"


def _col(i: int) -> str:
    name = ""
    i += 1
    while i:
        i, rem = divmod(i - 1, 26)
        name = chr(65 + rem) + name
    return name


def _xlsx_cell(ds: Dataset, ref: str, column: str, v: str) -> str:
    if column in ds.decimals:
        try:
            Decimal(v)
            return f'<c r="{ref}"><v>{v}</v></c>'  # a numeric cell, exact text as written
        except ArithmeticError:
            pass
    if column in ds.dates:
        try:
            serial = (date.fromisoformat(v) - _XLSX_EPOCH).days
            return f'<c r="{ref}" s="1"><v>{serial}</v></c>'  # a date-formatted serial
        except ValueError:
            pass  # a bad date stays text, as a user would have typed it
    return f'<c r="{ref}" t="inlineStr"><is><t>{escape(v)}</t></is></c>'


def _xlsx(ds: Dataset, t: Table, variant: str | None) -> bytes:
    header = "".join(
        f'<c r="{_col(i)}1" t="inlineStr"><is><t>{escape(c)}</t></is></c>'
        for i, c in enumerate(t[0])
    )
    rows = [f'<row r="1">{header}</row>']
    for n, r in enumerate(t[1], start=2):
        cells = "".join(_xlsx_cell(ds, f"{_col(i)}{n}", c, r[c]) for i, c in enumerate(t[0]))
        rows.append(f'<row r="{n}">{cells}</row>')
    xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    parts = {
        "[Content_Types].xml": xml
        + '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.'
        'relationships+xml"/><Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-'
        'officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/'
        'sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.'
        'worksheet+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.'
        'openxmlformats-officedocument.spreadsheetml.styles+xml"/><Override PartName="/docProps/'
        'core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>'
        "</Types>",
        "_rels/.rels": xml + f'<Relationships xmlns="{_PKG}">'
        f'<Relationship Id="rId1" Type="{_REL}/officeDocument" Target="xl/workbook.xml"/>'
        '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/'
        'relationships/metadata/core-properties" Target="docProps/core.xml"/></Relationships>',
        "docProps/core.xml": xml + '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.'
        'org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/">'
        f"<dc:title>{escape(_marker_line(ds, variant))}</dc:title>"
        f"<dc:creator>{GENERATOR}</dc:creator></cp:coreProperties>",
        "xl/workbook.xml": xml + f'<workbook xmlns="{_NS}" xmlns:r="{_REL}"><sheets>'
        f'<sheet name="{SHEET_NAME}" sheetId="1" r:id="rId1"/></sheets></workbook>',
        "xl/_rels/workbook.xml.rels": xml + f'<Relationships xmlns="{_PKG}">'
        f'<Relationship Id="rId1" Type="{_REL}/worksheet" Target="worksheets/sheet1.xml"/>'
        f'<Relationship Id="rId2" Type="{_REL}/styles" Target="styles.xml"/></Relationships>',
        "xl/styles.xml": xml + f'<styleSheet xmlns="{_NS}">'
        '<fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts>'
        '<fills count="2"><fill><patternFill patternType="none"/></fill>'
        '<fill><patternFill patternType="gray125"/></fill></fills>'
        '<borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders>'
        '<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/>'
        '</cellStyleXfs><cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"'
        ' xfId="0"/><xf numFmtId="14" fontId="0" fillId="0" borderId="0" xfId="0"'
        ' applyNumberFormat="1"/></cellXfs><cellStyles count="1"><cellStyle name="Normal"'
        ' xfId="0" builtinId="0"/></cellStyles></styleSheet>',
        "xl/worksheets/sheet1.xml": xml
        + f'<worksheet xmlns="{_NS}"><sheetData>'
        + "".join(rows)
        + "</sheetData></worksheet>",
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as zf:
        for name, content in parts.items():
            info = zipfile.ZipInfo(name, date_time=_FIXED_TIME)
            info.external_attr = 0o644 << 16
            zf.writestr(info, content.encode("utf-8"))
    return buffer.getvalue()


def _render(ds: Dataset, t: Table, variant: str | None) -> bytes:
    if ds.fmt == "xlsx":
        return _xlsx(ds, t, variant)
    text = _csv(ds, t, variant) if ds.fmt == "csv" else _json(ds, t, variant)
    return text.encode("cp1252" if variant == "non_utf8" else "utf-8")


def build() -> dict[str, bytes]:
    """Every sample file name -> its bytes. Pure: the same output on every run."""
    files: dict[str, bytes] = {}
    for ds in DATASETS:
        rng = random.Random(f"{SEED}:{ds.name}")
        table: Table = (list(ds.columns), [ds.make_row(rng, i) for i in range(1, ROWS + 1)])
        files[f"{ds.name}.{ds.fmt}"] = _render(ds, table, None)
        for variant, apply in VARIANTS.items():
            if variant in TEXT_ONLY and ds.fmt == "xlsx":
                continue
            files[f"{ds.name}__{variant}.{ds.fmt}"] = _render(ds, apply(ds, table), variant)
    sums = "".join(f"{hashlib.sha256(b).hexdigest()}  {n}\n" for n, b in sorted(files.items()))
    files["SHA256SUMS"] = sums.encode()
    return files


def write(out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, content in build().items():
        path = out / name
        path.write_bytes(content)
        written.append(path)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT, help=f"output directory ({OUT})")
    parser.add_argument("--check", action="store_true", help="fail if --out is out of date")
    args = parser.parse_args()
    if args.check:
        stale = [
            n
            for n, b in build().items()
            if not (args.out / n).exists() or (args.out / n).read_bytes() != b
        ]
        if stale:
            print(f"synthetic samples out of date ({', '.join(stale)}): run the generator")
            return 1
        print("synthetic samples are up to date")
        return 0
    paths = write(args.out)
    print(f"wrote {len(paths)} files to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
